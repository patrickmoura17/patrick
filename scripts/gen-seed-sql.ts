// Generates supabase/migrations/0003_seed.sql (roles, pipeline, settings, pricing
// catalog, templates, automations) from the same seed used in local mode.
//   npx tsx scripts/gen-seed-sql.ts
import { writeFileSync } from "node:fs";
import { buildSeed } from "../src/lib/seed";

const TABLES = ["company_settings", "roles", "pipeline_stages", "catalog_items", "estimate_templates", "automations"] as const;
const JSONB = new Set(["default_payment_schedule", "number_prefixes", "next_numbers", "items", "conditions", "actions"]);
const ARR = new Set(["permissions"]);

const lit = (col: string, v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (JSONB.has(col)) return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  if (ARR.has(col)) return `array[${(v as string[]).map((x) => `'${x}'`).join(",")}]::text[]`;
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};

(async () => {
  const S = await buildSeed({ demo: false, companyName: "Your Company" });
  let sql = "-- Generated by scripts/gen-seed-sql.ts — default configuration for a new company.\n\n";
  for (const t of TABLES) {
    for (const row of S[t] as unknown as Record<string, unknown>[]) {
      const r = { ...row };
      delete r.created_at;
      const cols = Object.keys(r);
      sql += `insert into public.${t} (${cols.map((c) => `"${c}"`).join(", ")}) values (${cols.map((c) => lit(c, r[c])).join(", ")});\n`;
    }
    sql += "\n";
  }
  writeFileSync("supabase/migrations/0003_seed.sql", sql);
  console.log("wrote supabase/migrations/0003_seed.sql");
})();
